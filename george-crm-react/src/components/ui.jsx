export function Icon({ api, name, ...props }) {
  const paths = {
    clock: (
      <>
        <circle cx="12" cy="12" r="9" />
        <path d="M12 7v5l3 2" />
      </>
    ),
    calendar: (
      <>
        <rect x="3" y="5" width="18" height="16" rx="2" />
        <path d="M7 3v4m10-4v4M3 11h18M8 15h2m4 0h2m-8 3h2" />
      </>
    ),
  };
  return paths[name] ? (
    <span className="rx-icon" aria-hidden="true" {...props}>
      <svg
        viewBox="0 0 24 24"
        fill="none"
        stroke="currentColor"
        strokeWidth="1.5"
        strokeLinecap="round"
        strokeLinejoin="round"
      >
        {paths[name]}
      </svg>
    </span>
  ) : (
    <span
      className="rx-icon"
      aria-hidden="true"
      {...props}
      dangerouslySetInnerHTML={{ __html: api.icon(name) }}
    />
  );
}
export function Status({ value, demo = false }) {
  const tone = /已处理|已确认|已绑定/.test(value)
    ? "success"
    : /驳回/.test(value)
      ? "danger"
      : /待处理|未确认/.test(value)
        ? "warning"
        : "neutral";
  return (
    <span className={`rx-status ${demo ? "neutral" : tone}`}>
      {demo ? "演示记录" : value || "编辑中"}
    </span>
  );
}
export function PageHeading({ title, description, actions, eyebrow }) {
  const compact = !eyebrow && ["待办中心", "企业微信通知", "客户管理", "线索管理"].includes(title);
  return (
    <header className={`rx-page-heading${compact ? " rx-page-heading--compact" : ""}`} aria-label={compact ? title : undefined}>
      {!compact && <div>
        {eyebrow && <div className="rx-eyebrow">{eyebrow}</div>}
        <h1>{title}</h1>
        <p>{description}</p>
      </div>}
      <div className="rx-heading-actions">{actions}</div>
    </header>
  );
}
