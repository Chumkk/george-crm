export function FragmentHtml({ html, className }) {
  return (
    <span
      className={className}
      dangerouslySetInnerHTML={{ __html: html || "" }}
    />
  );
}
export function CompatibilityView({ surface, api }) {
  const ref = useRef(null);
  useLayoutEffect(() => {
    ref.current.innerHTML = surface.html || "";
    api.afterLegacyMount();
    return attachManagementHeader(ref.current);
  }, [surface.html, surface.revision, api]);
  return (
    <div
      className="rx-compat-view"
      ref={ref}
      data-react-feature={surface.kind}
    />
  );
}
export class ErrorBoundary extends Component {
  state = { error: null };
  static getDerivedStateFromError(error) {
    return { error };
  }
  render() {
    return this.state.error ? (
      <div className="rx-error" role="alert">
        <h2>页面暂时无法显示</h2>
        <p>已保存的数据会保留，请刷新页面后重试。</p>
        <button className="rx-btn primary" onClick={() => location.reload()}>
          重新加载
        </button>
      </div>
    ) : (
      this.props.children
    );
  }
}
